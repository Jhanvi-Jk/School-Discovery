-- Helper: update fees by school name
CREATE OR REPLACE FUNCTION _set_fees(p_name TEXT, p_min INT, p_max INT)
RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
  UPDATE school_details sd
  SET total_fees_min = p_min, total_fees_max = p_max
  FROM schools s
  WHERE sd.school_id = s.id
    AND s.name = p_name
    AND (sd.total_fees_min IS NULL OR sd.total_fees_min = 0);
END $$;

