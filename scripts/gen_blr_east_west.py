"""Generate migration 049 from supabase/data/blr_east_west_2026_11.json (+ checked map pins)."""
import json, sys
src, geo_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
data = json.load(open(src))["schools"]
geo = json.load(open(geo_path))
REJECT_GEO = {"explorers-academy-gunjur"}  # OSM match was a different school ("Little Explorers Academy")
q = lambda v: "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"
arr = lambda xs: "ARRAY[" + ",".join(q(x) for x in xs) + "]::TEXT[]" if xs else "'{}'::TEXT[]"
L = ["-- Migration 049 — new Bengaluru East/West schools (generated by scripts/gen_blr_east_west.py; do not edit by hand).",
     "-- Facts: CBSE SARAS register + each school's own website, checked 2026-11-17. Gaps are listed in school_details.unconfirmed.",
     "BEGIN;"]
for s in data:
    slug = s["slug"]
    sel = f"(SELECT id FROM schools WHERE slug = {q(slug)})"
    top = "Class 12" if s["level"] == "SS" else "Class 10"
    if s["board"] == "cbse":
        desc = f"{s['name']} is affiliated to CBSE up to {top} (affiliation no. {s['aff']}) and is run by the {s['trust']}."
        if "established_year" not in s["unconfirmed"]:
            desc += f" CBSE records give {s['year']} as its year of foundation."
    else:
        desc = f"{s['name']} is an ICSE school affiliated to CISCE, New Delhi, run by the {s['trust']}, with pre-primary, primary and secondary sections."
    g = None if slug in REJECT_GEO else geo.get(slug)
    note = "Added 2026-11 from the CBSE SARAS register and the school's website." + (" " + s["note"] if s.get("note") else "")
    L.append(f"\n-- {s['name']} ({s['area']})")
    L.append("INSERT INTO schools (slug, name, description, established_year, type, gender, area, address_line1, city, pincode, website, phone, email, latitude, longitude, verified, affiliation_no, source_urls, listing_note, last_data_updated_at)")
    L.append(f"VALUES ({q(slug)}, {q(s['name'])}, {q(desc)}, {s['year'] if 'established_year' not in s['unconfirmed'] else 'NULL'}, 'private', {q(s['gender'])}, {q(s['area'])}, {q(s['address'])}, 'Bengaluru', {q(s['pincode'])}, {q(s['website'])}, {q(s['phone'])}, {q(s['email'])}, {g[0] if g else 'NULL'}, {g[1] if g else 'NULL'}, FALSE, {q(s['aff'])}, {arr(s['sources'])}, {q(note)}, NOW())")
    L.append("ON CONFLICT (slug) DO NOTHING;")
    tr = "NULL" if s["transport"] is None else ("TRUE" if s["transport"] else "FALSE")
    L.append(f"INSERT INTO school_details (school_id, has_transport, student_count, unconfirmed) SELECT {sel}, {tr}, {s.get('students') or 'NULL'}, {arr(s['unconfirmed'])} ON CONFLICT (school_id) DO NOTHING;")
    L.append(f"INSERT INTO school_curricula (school_id, curriculum) SELECT {sel}, {q(s['board'])} ON CONFLICT DO NOTHING;")
    L.append(f"INSERT INTO school_grades (school_id, grade_from, grade_to, curriculum) SELECT {sel}, {q(s['from'])}, {q(s['to'])}, {q(s['board'])} ON CONFLICT DO NOTHING;")
    if s["sports"]:
        L.append(f"INSERT INTO school_sports (school_id, sport_id) SELECT {sel}, id FROM sports WHERE name IN ({','.join(q(x) for x in s['sports'])}) ON CONFLICT DO NOTHING;")
    if s["extras"]:
        L.append(f"INSERT INTO school_extracurriculars (school_id, extracurricular_id) SELECT {sel}, id FROM extracurriculars WHERE name IN ({','.join(q(x) for x in s['extras'])}) ON CONFLICT DO NOTHING;")
    for lang, kind in s["languages"]:
        L.append(f"INSERT INTO school_languages (school_id, language, type) SELECT {sel}, {q(lang)}, {q(kind)} ON CONFLICT DO NOTHING;")
    for st in s["streams"]:
        L.append(f"INSERT INTO school_subjects (school_id, kind, name) SELECT {sel}, 'stream', {q(st)} ON CONFLICT DO NOTHING;")
L += ["\nCOMMIT;", "NOTIFY pgrst, 'reload schema';"]
open(out, "w").write("\n".join(L) + "\n")
print(len(data), "schools,", sum(1 for s in data if geo.get(s['slug']) and s['slug'] not in REJECT_GEO), "with map pins")
